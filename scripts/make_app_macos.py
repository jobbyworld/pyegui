"""Create an .app for a pyegui app (the Finder example by default), LINKED to this source tree.

    python scripts/make_app_macos.py                          # -> ~/Applications/Finder.app
    python scripts/make_app_macos.py --dest /Applications --python /path/to/python
    python scripts/make_app_macos.py examples/app.py --name Atelier --icon my.icns --bundle-id org.pyegui.Atelier

The bundle only contains a launcher script, an Info.plist and the icon: editing the code never
requires rebuilding the app. Rebuild it only if the repository or the venv moves.
Launcher output goes to ~/Library/Logs/<name>/launcher.log.

The framework's Python.app binary is COPIED into the bundle (and re-signed ad hoc): macOS
(Dock, Stage Manager thumbnails, app switcher) takes the icon and name from the bundle that
contains the running executable, which would otherwise be Python.app (the rocket icon).
``__PYVENV_LAUNCHER__`` makes the copy use the venv, as the venv's own python stub does.
Drag the .app to the Dock to pin it.
"""

from __future__ import annotations

import argparse
import plistlib
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_SCRIPT = REPO / "examples" / "finder.py"
DEFAULT_ICON = REPO / "examples" / "app_icon" / "finder.icns"
DEFAULT_NAME = "Finder"
DEFAULT_BUNDLE_ID = "org.pyegui.Finder"
VERSION = "1.0"
LSREGISTER = (
    "/System/Library/Frameworks/CoreServices.framework/Frameworks/"
    "LaunchServices.framework/Support/lsregister"
)

LAUNCHER = """#!/bin/bash
# Generated by scripts/make_app_macos.py - linked to the source tree, do not edit.
SCRIPT={script}
PY={python}
LOG_DIR="$HOME/Library/Logs/{name}"
mkdir -p "$LOG_DIR"
if [ ! -x "$PY" ]; then
  /usr/bin/osascript -e 'display alert "{name}" message "Python not found: '"$PY"'. Recreate the venv and run scripts/make_app_macos.py again."'
  exit 1
fi
cd "$(dirname "$SCRIPT")" || exit 1
BIN="$(dirname "$0")/{name}-python"
if [ -x "$BIN" ]; then
  export __PYVENV_LAUNCHER__="$PY"
  exec "$BIN" "$SCRIPT" "$@" >>"$LOG_DIR/launcher.log" 2>&1
fi
exec "$PY" "$SCRIPT" "$@" >>"$LOG_DIR/launcher.log" 2>&1
"""


def _framework_binary(python: Path) -> Path | None:
    """The real executable behind a (venv) python, when it is a macOS framework build."""
    out = subprocess.run(
        [str(python), "-c", "import sys; print(sys.base_prefix)"],
        capture_output=True,
        text=True,
        check=False,
    ).stdout.strip()
    binary = Path(out) / "Resources" / "Python.app" / "Contents" / "MacOS" / "Python"
    return binary if out and binary.is_file() else None


def build_bundle(
    dest_dir: Path,
    script: Path = DEFAULT_SCRIPT,
    name: str = DEFAULT_NAME,
    icon: Path = DEFAULT_ICON,
    bundle_id: str = DEFAULT_BUNDLE_ID,
    python: Path | None = None,
) -> Path:
    python = python or REPO / ".venv" / "bin" / "python"  # not resolved: keep the venv symlink
    app = Path(dest_dir).expanduser() / f"{name}.app"
    if app.exists():
        shutil.rmtree(app)
    macos, resources = app / "Contents" / "MacOS", app / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir(parents=True)

    launcher = macos / name
    launcher.write_text(
        LAUNCHER.format(
            script=shlex.quote(script.resolve().as_posix()),
            python=shlex.quote(python.as_posix()),
            name=name,
        ),
        encoding="utf-8",
    )
    launcher.chmod(0o755)
    binary = _framework_binary(python) if sys.platform == "darwin" else None
    if binary is not None:
        copy = macos / f"{name}-python"
        shutil.copyfile(binary, copy)
        copy.chmod(0o755)
        subprocess.run(
            ["codesign", "--force", "--sign", "-", str(copy)], check=False, capture_output=True
        )  # the copied signature no longer matches: killed
    shutil.copyfile(icon, resources / f"{name}.icns")
    info = {
        "CFBundleName": name,
        "CFBundleDisplayName": name,
        "CFBundleIdentifier": bundle_id,
        "CFBundleExecutable": name,
        "CFBundleIconFile": name,
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": VERSION,
        "CFBundleVersion": VERSION,
        "LSMinimumSystemVersion": "11.0",
        "NSHighResolutionCapable": True,
        "NSRequiresAquaSystemAppearance": False,  # follow dark mode
    }
    with open(app / "Contents" / "Info.plist", "wb") as fh:
        plistlib.dump(info, fh)
    return app


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("script", nargs="?", type=Path, default=DEFAULT_SCRIPT, help="the app to start (default: examples/finder.py)")
    ap.add_argument("--name", default=DEFAULT_NAME, help="name of the app (default: Finder)")
    ap.add_argument("--icon", type=Path, default=DEFAULT_ICON, help=".icns file of the app")
    ap.add_argument("--bundle-id", default=DEFAULT_BUNDLE_ID)
    ap.add_argument("--dest", type=Path, default=Path.home() / "Applications")
    ap.add_argument("--python", type=Path, default=None, help="interpreter to use (default: <repo>/.venv/bin/python)")
    args = ap.parse_args(argv)
    python = args.python or REPO / ".venv" / "bin" / "python"
    if not args.script.exists():
        print(f"Not found: {args.script}")
        return 1
    if not python.exists():
        print(
            f"Python not found: {python}\n"
            "Create the venv first: python3 -m venv .venv && .venv/bin/pip install maturin "
            "&& .venv/bin/maturin develop --release"
        )
        return 1
    args.dest.expanduser().mkdir(parents=True, exist_ok=True)
    app = build_bundle(args.dest, args.script, args.name, args.icon, args.bundle_id, python)
    if sys.platform == "darwin":
        subprocess.run([LSREGISTER, "-f", str(app)], check=False)  # refresh icon and name
        subprocess.run(["touch", str(app)], check=False)
    print(f"App created: {app}\nDrag it to the Dock to pin it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
